def delete_lesson(ref: str | int) -> bool:
    les = get_lesson_any(ref)
    if not les:
        return False
    with db.conn() as c:
        c.execute("DELETE FROM academy_progress WHERE lesson_code=?", (les["code"],))
        cur = c.execute("DELETE FROM academy_lessons WHERE id=?", (int(les["id"]),))
        return cur.rowcount > 0


def toggle_lesson_track(ref: str | int) -> str | None:
    les = get_lesson_any(ref)
    if not les:
        return None
    nxt = "FREE" if str(les["track"]).upper() == "PAID" else "PAID"
    with db.conn() as c:
        c.execute(
            "UPDATE academy_lessons SET track=?, edited_by_admin=1, updated_at=? WHERE id=?",
            (nxt, config.now(), int(les["id"])),
        )
    return nxt


def toggle_lesson_enabled(ref: str | int) -> bool | None:
    les = get_lesson_any(ref)
    if not les:
        return None
    nxt = 0 if int(les.get("enabled") or 0) == 1 else 1
    with db.conn() as c:
        c.execute(
            "UPDATE academy_lessons SET enabled=?, edited_by_admin=1, updated_at=? WHERE id=?",
            (nxt, config.now(), int(les["id"])),
        )
    return bool(nxt)


