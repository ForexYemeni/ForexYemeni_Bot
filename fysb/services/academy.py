def submit_quiz_answer(user_id: int, lesson_ref: str | int, opt_idx: int, q_idx: int = 0) -> dict:
    """Evaluate a student's quiz choice for question `q_idx` (0-indexed).
    Marks the lesson complete once the final question is passed (100% PG & SQLite safe)."""
    les = get_lesson_any(lesson_ref)
    if not les:
        return {"ok": False, "error": "lesson_not_found"}
    quiz = les.get("quiz") or []
    total_q = len(quiz)
    if not quiz or q_idx < 0 or q_idx >= total_q:
        mark_lesson_complete(user_id, les["code"], max(1, total_q), max(1, total_q))
        return {
            "ok": True,
            "correct": True,
            "q_idx": 0,
            "total_questions": total_q,
            "next_q_idx": None,
            "completed_lesson": True,
            "explanation": "",
            "lesson": les,
        }
    q_item = quiz[q_idx]
    expected = int(q_item.get("ans", 0))
    opts = q_item.get("opts") or []
    correct = int(opt_idx) == expected
    next_q_idx = (q_idx + 1) if (correct and q_idx + 1 < total_q) else None
    completed_lesson = bool(correct and next_q_idx is None)
    if completed_lesson:
        mark_lesson_complete(user_id, les["code"], total_q, total_q)
    return {
        "ok": True,
        "correct": correct,
        "q_idx": q_idx,
        "total_questions": total_q,
        "next_q_idx": next_q_idx,
        "completed_lesson": completed_lesson,
        "explanation": str(q_item.get("exp") or ""),
        "expected_idx": expected,
        "expected_text": opts[expected] if 0 <= expected < len(opts) else "",
        "lesson": les,
    }


def mark_lesson_complete(user_id: int, lesson_code: str, quiz_score: int = 1, quiz_total: int = 1) -> None:
    """PostgreSQL & SQLite 100% portable completion upsert (no SQLite-only MAX(a,b)!)."""
    now_iso = config.now()
    with db.conn() as c:
        c.execute(
            """INSERT INTO academy_progress(user_id,lesson_code,completed,quiz_score,quiz_total,completed_at)
               VALUES(?,?,1,?,?,?)
               ON CONFLICT(user_id,lesson_code) DO UPDATE SET
                 completed=1,
                 quiz_score=CASE
                   WHEN excluded.quiz_score > academy_progress.quiz_score
                   THEN excluded.quiz_score
                   ELSE academy_progress.quiz_score
                 END,
                 quiz_total=excluded.quiz_total,
                 completed_at=excluded.completed_at""",
            (int(user_id), lesson_code, int(quiz_score), max(1, int(quiz_total)), now_iso),
        )


def user_progress(user_id: int) -> dict:
    ensure_seeded()
    all_les = list_lessons()
    free_codes = [l["code"] for l in all_les if str(l["track"]).upper() == "FREE"]
    paid_codes = [l["code"] for l in all_les if str(l["track"]).upper() == "PAID"]
    with db.conn() as c:
        rows = c.execute(
            "SELECT lesson_code, completed, quiz_score, quiz_total FROM academy_progress WHERE user_id=? AND completed=1",
            (int(user_id),),
        ).fetchall()
    done = {r["lesson_code"] for r in rows}
    free_done = sum(1 for code in free_codes if code in done)
    paid_done = sum(1 for code in paid_codes if code in done)
    total_done = free_done + paid_done
    total_all = len(free_codes) + len(paid_codes)
    free_pct = round(free_done / len(free_codes) * 100.0, 1) if free_codes else 0.0
    paid_pct = round(paid_done / len(paid_codes) * 100.0, 1) if paid_codes else 0.0
    overall_pct = round(total_done / total_all * 100.0, 1) if total_all else 0.0
    paid_access = has_paid_access(user_id)
    cert_ready_free = len(free_codes) > 0 and free_done >= len(free_codes)
    cert_ready_paid = paid_access and len(paid_codes) > 0 and paid_done >= len(paid_codes)
    return {
        "completed_codes": done,
        "free_done": free_done,
        "free_total": len(free_codes),
        "free_pct": free_pct,
        "paid_done": paid_done,
        "paid_total": len(paid_codes),
        "paid_pct": paid_pct,
        "total_done": total_done,
        "total_all": total_all,
        "overall_pct": overall_pct,
        "has_paid": paid_access,
        "cert_ready_free": cert_ready_free,
        "cert_ready_paid": cert_ready_paid,
    }


