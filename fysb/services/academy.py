def seed_default_lessons() -> int:
    """Idempotently seed all 15 institutional masterclasses without overwriting Admin edits."""
    inserted = 0
    now_iso = config.now()
    with db.conn() as c:
        for les in DEFAULT_LESSONS:
            exists = c.execute("SELECT id, edited_by_admin FROM academy_lessons WHERE code=?", (les["code"],)).fetchone()
            if not exists:
                c.execute(
                    """INSERT INTO academy_lessons
                       (code,title,track,sort_order,summary,content,quiz_json,
                        media_type,media_file_id,media_caption,edited_by_admin,enabled,updated_at)
                       VALUES(?,?,?,?,?,?,?,'TEXT','','',0,1,?)""",
                    (
                        les["code"], les["title"], les["track"], les["sort_order"],
                        les["summary"], les["content"], json.dumps(les["quiz"], ensure_ascii=False),
                        now_iso,
                    ),
                )
                inserted += 1
    return inserted


def upgrade_default_curriculum() -> int:
    """Seamlessly upgrade unmodified default lessons to CURRICULUM_VERSION without
    touching any lesson edited or added by Admin (`edited_by_admin = 1`)."""
    updated = 0
    now_iso = config.now()
    with db.conn() as c:
        for les in DEFAULT_LESSONS:
            row = c.execute(
                "SELECT id, edited_by_admin FROM academy_lessons WHERE code=?",
                (les["code"],),
            ).fetchone()
            if not row:
                c.execute(
                    """INSERT INTO academy_lessons
                       (code,title,track,sort_order,summary,content,quiz_json,
                        media_type,media_file_id,media_caption,edited_by_admin,enabled,updated_at)
                       VALUES(?,?,?,?,?,?,?,'TEXT','','',0,1,?)""",
                    (
                        les["code"], les["title"], les["track"], les["sort_order"],
                        les["summary"], les["content"], json.dumps(les["quiz"], ensure_ascii=False),
                        now_iso,
                    ),
                )
                updated += 1
            elif int(row["edited_by_admin"] or 0) == 0:
                c.execute(
                    """UPDATE academy_lessons
                       SET title=?, summary=?, content=?, quiz_json=?, updated_at=?
                       WHERE id=?""",
                    (
                        les["title"], les["summary"], les["content"],
                        json.dumps(les["quiz"], ensure_ascii=False),
                        now_iso, int(row["id"]),
                    ),
                )
                updated += 1
    db.set_setting("academy_curriculum_version", CURRICULUM_VERSION)
    return updated


def ensure_seeded() -> None:
    with db.conn() as c:
        cnt = c.execute("SELECT COUNT(*) n FROM academy_lessons").fetchone()["n"]
    if cnt == 0:
        seed_default_lessons()
        db.set_setting("academy_curriculum_version", CURRICULUM_VERSION)
    elif (db.get_setting("academy_curriculum_version", "") or "") != CURRICULUM_VERSION:
        upgrade_default_curriculum()


def _hydrate_lesson(r) -> dict | None:
    if not r:
        return None
    d = dict(r)
    try:
        d["quiz"] = json.loads(d.get("quiz_json") or "[]")
    except Exception:
        d["quiz"] = []
    d["media_type"] = str(d.get("media_type") or "TEXT").upper()
    d["media_file_id"] = str(d.get("media_file_id") or "")
    d["media_caption"] = str(d.get("media_caption") or "")
    return d


def list_lessons(track: str | None = None, include_disabled: bool = False) -> list[dict]:
    ensure_seeded()
    sql = "SELECT * FROM academy_lessons WHERE 1=1"
    args: list = []
    if not include_disabled:
        sql += " AND enabled=1"
    if track:
        sql += " AND UPPER(track)=?"
        args.append(track.strip().upper())
    sql += " ORDER BY sort_order ASC, id ASC"
    with db.conn() as c:
        rows = [_hydrate_lesson(r) for r in c.execute(sql, tuple(args)).fetchall()]
    return [r for r in rows if r]


def get_lesson(code: str) -> dict | None:
    ensure_seeded()
    with db.conn() as c:
        r = c.execute("SELECT * FROM academy_lessons WHERE code=?", (str(code).strip(),)).fetchone()
    return _hydrate_lesson(r)


def get_lesson_by_id(lid: int) -> dict | None:
    ensure_seeded()
    with db.conn() as c:
        r = c.execute("SELECT * FROM academy_lessons WHERE id=?", (int(lid),)).fetchone()
    return _hydrate_lesson(r)


def get_lesson_any(ref: str | int) -> dict | None:
    """Resolve a lesson by numeric ID or string code seamlessly."""
    s = str(ref or "").strip()
    if not s:
        return None
    if s.isdigit():
        found = get_lesson_by_id(int(s))
        if found:
            return found
    return get_lesson(s)


def next_lesson_in_track(ref: str | int) -> dict | None:
    cur = get_lesson_any(ref)
    if not cur:
        return None
    lessons = list_lessons(track=cur["track"], include_disabled=False)
    for idx, les in enumerate(lessons):
        if les["id"] == cur["id"] and idx + 1 < len(lessons):
            return lessons[idx + 1]
    return None


def create_lesson(
    title: str,
    track: str = "PAID",
    content: str = "",
    summary: str = "",
    media_type: str = "TEXT",
    media_file_id: str = "",
    media_caption: str = "",
    quiz: list[dict] | None = None,
) -> dict:
    """Create a brand-new Admin custom lesson (TEXT / VIDEO / AUDIO / VOICE / PDF / PHOTO)."""
    ensure_seeded()
    t_norm = "FREE" if str(track or "").strip().upper() == "FREE" else "PAID"
    m_type = str(media_type or "TEXT").strip().upper()
    if m_type not in MEDIA_BADGES:
        m_type = "TEXT"
    title_clean = (title or "درس جديد").strip()[:140]
    content_clean = (content or "").strip()
    summary_clean = (summary or content_clean[:120]).strip()[:200]
    quiz_list = quiz if isinstance(quiz, list) else []
    code = f"C_{t_norm[0]}_{secrets.token_hex(3).upper()}"
    now_iso = config.now()
    with db.conn() as c:
        mx = c.execute("SELECT COALESCE(MAX(sort_order), 0) m FROM academy_lessons").fetchone()["m"]
        sort_order = int(mx or 0) + 1
        cur = c.execute(
            """INSERT INTO academy_lessons
               (code,title,track,sort_order,summary,content,quiz_json,
                media_type,media_file_id,media_caption,edited_by_admin,enabled,updated_at)
               VALUES(?,?,?,?,?,?,?,?,?,?,1,1,?)""",
            (
                code, title_clean, t_norm, sort_order, summary_clean, content_clean,
                json.dumps(quiz_list, ensure_ascii=False),
                m_type, str(media_file_id or "").strip(), str(media_caption or "").strip()[:240],
                now_iso,
            ),
        )
        new_id = cur.lastrowid
    return get_lesson_by_id(new_id) or get_lesson(code)


def update_lesson_content(ref: str | int, title: str | None = None, content: str | None = None, summary: str | None = None) -> dict | None:
    les = get_lesson_any(ref)
    if not les:
        return None
    new_title = title.strip()[:140] if title is not None and title.strip() else les["title"]
    new_content = content.strip() if content is not None else les["content"]
    new_summary = summary.strip()[:200] if summary is not None else les["summary"]
    with db.conn() as c:
        c.execute(
            """UPDATE academy_lessons
               SET title=?, content=?, summary=?, edited_by_admin=1, updated_at=?
               WHERE id=?""",
            (new_title, new_content, new_summary, config.now(), int(les["id"])),
        )
    return get_lesson_by_id(les["id"])


